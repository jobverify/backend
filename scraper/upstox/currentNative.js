const SOURCE = 'upstox', ROOT = 'https://upstox.com/careers/'
const CLIENT = 'https://upstox.com/marketing-page-assets/_next/static/chunks/app/careers/page-5e7eafca29b164c3.js'
const CLIENT_SHA = '7895a7302bb2c196230b0fb0a656a833b7a505936bf6f0af7e7a73506c8e2a16'
const FEED = 'https://service.upstox.com/content/open/v1/jobs/'
const NATIVE = 'https://upstox.darwinbox.in'
const NATIVE_CLIENT = NATIVE + '/ms/candidatev2/main.aad4e9f12624d60f.js'
const NATIVE_SHA = '7d18a53b8cde72423e953eee67317dd245113c4ed0078dbfa65376d04354cfe1'
const COMPANY = NATIVE + '/ms/candidateapi/getCompanyConfig?is_preview=false&companyId=main'
const chrome = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/138.0.0.0 Safari/537.36'
const sha = value => createHash('sha256').update(value).digest('hex')
const failure = message => firstPartyFailure(SOURCE, message, { failureKind: 'coverage_gap', nativeAuthorityFailure: true })
const need = (value, message) => { if (!value) throw failure(message) }
export const hasCurrentUpstoxClient = html => String(html).includes(new URL(CLIENT).pathname)

function inspect(html) {
  const page = qualifiedFirstPartyHTML(html, ROOT, failure)
  need(page.title === 'Careers – Latest Opening at Upstox'
    && page.visible.nodes(node => node.tag === 'h1' && page.visible.text(node) === 'Upstox Careers').length === 1,
  'Native current publisher identity changed')
  need(page.raw.nodes(node => node.tag === 'script' && node.attrs.src === new URL(CLIENT).pathname
    && !Object.hasOwn(node.attrs, 'nomodule') && /^(?:|module|(?:text|application)\/javascript)$/i.test(node.attrs.type || '')).length === 1,
  'Current executable client declaration changed')
  const scripts = page.raw.nodes(node => node.tag === 'script' && !node.attrs.src && !Object.hasOwn(node.attrs, 'nomodule')
    && /^(?:|module|(?:text|application)\/javascript)$/i.test(node.attrs.type || ''))
  const records = readLiteralFlightRecords(scripts.map(node => '<script>' + node.raw + '</script>').join(''))
  const declaration = records?.get('13')?.raw
  need(typeof declaration === 'string' && declaration.startsWith('I['), 'Native current view module missing')
  const imported = JSON.parse(declaration.slice(1))
  need(imported[0] === 602 && imported[2] === 'CareersClient' && imported[1].includes('static/chunks/app/careers/page-5e7eafca29b164c3.js'),
    'Native rendered view owner changed')
  const root = records.get('7')?.value
  const views = root?.[0] === '$' && root[1] === 'div' && Array.isArray(root[3]?.children)
    ? root[3].children.filter(child => Array.isArray(child) && child[0] === '$' && child[1] === '$L13' && Array.isArray(child[3]?.initialJobs)) : []
  need(views.length === 1, 'Native current view model unavailable or ambiguous')
  const models = views[0][3].initialJobs
  need(models.length > 0 && models.length <= 500 && models.every(row => row?.isActive === true && /^[a-z\d]+$/i.test(row.id) && typeof row.title === 'string'),
    'Native rendered role identity or publication changed')
  const cards = page.visible.nodes(node => node.tag === 'div' && node.attrs.role === 'button' && (node.attrs.class || '').split(/\s+/).includes('group'))
  const titles = cards.map(node => page.visible.text(node.children.filter(child => typeof child !== 'string')
    .flatMap(function headings(child) { return [child, ...child.children.filter(next => typeof next !== 'string').flatMap(headings)] })
    .find(child => child.tag === 'h3')))
  need(titles.length === models.length && models.every((row, index) => row.title === titles[index]), 'Native rendered listing and active cards changed')
  return { models, html }
}

// The current first-party feed publishes 57 original models, but its card
// summaries are generated by the reviewed mapper. Preserve those observations
// when native full criteria are denied; never promote the summaries to JDs.
export async function runCurrentUpstox(options = {}) {
  options.signal?.throwIfAborted()
  const signal = AbortSignal.any([AbortSignal.timeout(120000), ...(options.signal ? [options.signal] : [])])
  const audit = { source: SOURCE, sourceScopeComplete: false, lifecycleCleanupAllowed: false,
    failures: [], receipts: [], fullRoleCriteriaQualified: false }
  const allowed = new Set([ROOT, CLIENT, FEED, NATIVE_CLIENT, COMPANY])
  let count = 0, aggregate = 0
  const read = async (url, type) => {
    signal.throwIfAborted(); need(allowed.has(url) && ++count <= 16, 'Unbound native request or budget reached')
    const packet = await boundedDeclaredPublicGet(url, { signal, overflowError: failure('Native entity exceeds byte limit'),
      fetchImpl: (requested, init) => (options.fetchImpl || globalThis.fetch)(requested, { ...init, credentials: 'omit', cache: 'no-store',
        headers: { ...init.headers, 'User-Agent': chrome } }) })
    const bytes = Buffer.from(packet.bodyBase64, 'base64'); aggregate += bytes.length
    audit.receipts.push({ requestedURL: url, finalURL: packet.url, status: packet.status, bytes: bytes.length, sha256: sha(bytes) })
    need(aggregate <= 16e6 && packet.url === url, 'Native response authority or byte budget changed')
    if (packet.status !== 200) throw Object.assign(failure('Native full-criteria service HTTP ' + packet.status), { status: packet.status })
    need((type === 'json' ? /application\/json/i : type === 'js' ? /(?:text|application)\/(?:java|ecma)script/i : /text\/html/i)
      .test(packet.headers['content-type'] || ''), 'Native MIME changed')
    const text = new TextDecoder('utf-8', { fatal: true }).decode(bytes)
    return { text, value: type === 'json' ? JSON.parse(text) : null }
  }
  try {
    const opening = inspect((await read(ROOT, 'html')).text)
    need(sha((await read(CLIENT, 'js')).text) === CLIENT_SHA, 'Current executable native program changed')
    const feed = await read(FEED, 'json'), payload = feed.value
    need(payload?.success === true && Array.isArray(payload.data) && payload.data.length <= 1000, 'Native feed error envelope')
    audit.originalPayload = structuredClone(payload); audit.originalPayloadText = feed.text
    const ids = new Set()
    for (const row of payload.data) {
      need(row && /^[a-z\d]+$/i.test(row.job_id || '') && !ids.has(row.job_id) && typeof row.job_title === 'string'
        && [0, 1].includes(row.post_on_careers_page), 'Native duplicate, incomplete identity or publication state')
      ids.add(row.job_id)
    }
    const published = payload.data.filter(row => row.post_on_careers_page === 1)
    need(published.length === opening.models.length && published.every(row => opening.models.some(model => model.id === row.job_id && model.title === row.job_title)),
      'Native publication identities conflict with current publisher view')
    need(published.every(row => ['UPSTOX', 'Upstox Securities Private Limited'].includes(row.group_company)
      && ['RKSV Securities India Private Limited', 'Upstox Securities Private Limited'].includes(row.business_unit)), 'Native employer account changed')
    Object.assign(audit, { originalPublicRecords: structuredClone(published), originalRenderedModels: structuredClone(opening.models),
      originalPublisherHTML: opening.html, unqualifiedPublicRoleIds: published.map(row => row.job_id) })
    const ownURL = NATIVE + '/ms/candidatev2/main/careers/jobDetails/' + published[0].job_id + '?from=all'
    allowed.add(ownURL)
    const own = await read(ownURL, 'html'), document = readNativeDocument(own.text)
    need(document.nodes(node => node.tag === 'base' && node.attrs.href === '/ms/candidatev2/').length === 1
      && document.nodes(node => node.tag === 'app-root').length === 1
      && document.nodes(node => node.tag === 'script' && node.attrs.src === 'main.aad4e9f12624d60f.js' && node.attrs.type === 'module').length === 1,
    'Native current full-role application renderer changed')
    need(sha((await read(NATIVE_CLIENT, 'js')).text) === NATIVE_SHA, 'Native full-role renderer program changed')
    audit.originalNativeApplicationHTML = own.text
    try {
      audit.originalNativeCompany = (await read(COMPANY, 'json')).value
      throw failure('Readable native full-role data requires a reviewed current own-record contract')
    } catch (error) {
      signal.throwIfAborted()
      if (![401, 403, 429, 451].includes(error.status)) throw error
      audit.failures.push({ stage: 'native-company-and-full-criteria', status: error.status, message: error.message })
    }
    const closingFeed = await read(FEED, 'json'), closing = inspect((await read(ROOT, 'html')).text)
    need(JSON.stringify(closingFeed.value?.data) === JSON.stringify(payload.data)
      && JSON.stringify(closing.models) === JSON.stringify(opening.models), 'Closing native listing or publication changed')
    audit.closingPayload = closingFeed.value; audit.closingPublisherHTML = closing.html
    const jobs = []
    attachSourceObservationEvidence(jobs, { source: SOURCE, recordKind: 'mixed', observedRecordCount: payload.data.length,
      observedVacancyCount: published.length, sourceScopeComplete: false, companyGlobalTotal: null, companyIndiaTotal: null })
    Object.defineProperty(jobs, 'nativeCollectionEvidence', { value: audit, configurable: true })
    options.signal?.throwIfAborted()
    return attachInventoryEvidence(jobs, { status: 'coverage-gap', surface: FEED, firstParty: true, listingComplete: false, lifecycleCleanupAllowed: false,
      pagesFetched: count, reportedTotal: published.length, indiaFacetCount: null, verifiedAt: null,
      reason: 'current-original-publisher-and-native-feed-reconciled;native-full-criteria-service-access-denied;generated-card-summaries-are-not-full-criteria;company-scope-unqualified;cleanup-forbidden' })
  } catch (error) { options.signal?.throwIfAborted(); error.sourceAudit = audit; throw error }
}
